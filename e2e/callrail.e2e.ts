/** Disposable local/CI data only. No CallRail or Google requests are made. */
import assert from "node:assert/strict";
import { createHmac } from "node:crypto";
import { after, before, test } from "node:test";
import { Prisma, PrismaClient } from "@prisma/client";
import { assertSafeE2eTarget, assertServerUsesTestDatabase } from "./guard";
import { reconcileLegacyGoogleAdsOutcomes } from "../src/features/google-ads/legacy-outcomes";
import { onProposalSent } from "../src/features/core/events";
import { closeSaleIfReady } from "../src/features/sales/close-sale";
import { prisma as runtimeDb } from "../src/lib/db";

const base = process.env.E2E_BASE_URL || "http://127.0.0.1:3000";
assertSafeE2eTarget(base);
const db = new PrismaClient();
const company = process.env.CALLRAIL_COMPANY_ID!;
const key = process.env.CALLRAIL_WEBHOOK_SIGNING_KEY!;
const tag = String(Date.now());
const ids: string[] = [];
const dealIds: string[] = [];
const clientIds: string[] = [];
let cookie = "";
let originalWorkspace: Prisma.JsonValue | null = null;
let originalSettings: any = null;
let snapshotReady = false;
function fixture(id: string, phone = "+12025550123") {
  return { id: `${tag}-${id}`, company_id: company, direction: "inbound", start_time: new Date().toISOString(), duration: 75, answered: true, customer_phone_number: phone, customer_name: "Offline CallRail fixture", source_name: "Google Ads", gclid: `offline-${tag}` };
}
async function send(body: unknown, signature?: string) {
  const raw = JSON.stringify(body);
  const response = await fetch(base + "/api/webhooks/callrail", { method: "POST", headers: { "content-type": "application/json", signature: signature ?? createHmac("sha1", key).update(raw).digest("base64") }, body: raw });
  return { status: response.status, body: await response.json() };
}
before(async () => {
  await assertServerUsesTestDatabase(base, db);
  assert.ok(company && key, "CallRail fixture configuration must be present on both test process and server");
  await db.user.updateMany({ where: { email: "owner@rolanpro.local" }, data: { must_change_password: false } });
  originalWorkspace = (await db.legacyWorkspace.findUnique({ where: { workspace_id: "primary" } }))?.payload ?? null;
  originalSettings = await db.googleAdsIntegrationSetting.findUnique({ where: { setting_key: "default" } });
  snapshotReady = true;
});
after(async () => {
  try {
  if (!snapshotReady) return;
  await db.conversionUploadOutbox.deleteMany({ where: { conversion_event: { lead_id: { in: ids } } } });
  await db.conversionEvent.deleteMany({ where: { lead_id: { in: ids } } });
  await db.activityLog.deleteMany({ where: { entity_id: { in: [...ids, ...dealIds] } } });
  await db.followUp.deleteMany({ where: { deal_id: { in: dealIds } } });
  await db.deal.deleteMany({ where: { deal_id: { in: dealIds } } });
  await db.client.deleteMany({ where: { client_id: { in: clientIds } } });
  await db.acquisitionTouchpoint.deleteMany({ where: { lead_id: { in: ids } } });
  await db.consentSnapshot.deleteMany({ where: { lead_id: { in: ids } } });
  await db.lead.deleteMany({ where: { lead_id: { in: ids } } });
  if (originalWorkspace) await db.legacyWorkspace.update({ where: { workspace_id: "primary" }, data: { payload: originalWorkspace as Prisma.InputJsonValue, revision: { increment: 1 } } });
  else await db.legacyWorkspace.deleteMany({ where: { workspace_id: "primary" } });
  if (originalSettings) {
    const { setting_key: _key, created_at: _created, updated_at: _updated, qualification_rules, audience_rules, ...settings } = originalSettings;
    await db.googleAdsIntegrationSetting.update({ where: { setting_key: "default" }, data: { ...settings, qualification_rules: qualification_rules ?? Prisma.DbNull, audience_rules: audience_rules ?? Prisma.DbNull } });
  } else await db.googleAdsIntegrationSetting.deleteMany({ where: { setting_key: "default" } });
  } finally {
    await db.$disconnect();
    await runtimeDb.$disconnect();
  }
});
test("signed calls deduplicate concurrently, preserve original source, and create no qualification", async () => {
  const login = await fetch(base + "/api/v1/auth/login", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ email: "owner@rolanpro.local", password: process.env.E2E_SEED_PASSWORD || "ChangeMe123!" }) });
  assert.equal(login.status, 200);
  cookie = login.headers.get("set-cookie")!.split(";")[0];
  const settings = { conversion_owner_customer_id: "900000002", qualified_lead_action_id: "100", converted_lead_action_id: "101", qualification_rules: { pipeline_status_code: "PROPOSAL_SENT" }, upload_enabled: false, validate_only: true };
  await db.googleAdsIntegrationSetting.upsert({ where: { setting_key: "default" }, create: { setting_key: "default", ...settings }, update: settings });
  const call = { ...fixture("first"), answered: null, duration: 64, call_type: "missed", spam: true };
  assert.equal((await send(call, "invalid")).status, 401);
  assert.equal((await send({ ...call, company_id: "another" })).status, 403);
  assert.equal((await send({ ...call, direction: "outbound" })).body.ignored, true);
  const results = await Promise.all([send(call), send(call)]);
  for (const result of results) assert.equal(result.status, 200);
  const leadId = results[0].body.lead_id;
  ids.push(leadId);
  const missed = await db.lead.findUniqueOrThrow({ where: { lead_id: leadId }, include: { pipeline_status: true } });
  assert.equal(missed.pipeline_status.status_code, "NEW_LEAD");
  assert.match(missed.notes!, /CallRail пометил как спам/);
  const receipt = await db.activityLog.findFirstOrThrow({ where: { entity_id: leadId, action_key: "integration.callrail.call" } });
  assert.equal((receipt.metadata as Record<string, unknown>).answered, null);
  const enriched = await fetch(base + "/api/v1/leads/" + leadId, { method: "PATCH", headers: { cookie, "content-type": "application/json" }, body: JSON.stringify({ name: "Enriched offline caller", email: "caller@example.invalid" }) });
  assert.equal(enriched.status, 200);
  assert.equal(await db.conversionEvent.count({ where: { lead_id: leadId } }), 0, "contact enrichment alone is not qualification");
  assert.equal(results[1].body.lead_id, leadId);
  assert.equal(results.filter(item => item.body.duplicate).length, 1);
  const second = await send(fixture("repeat"));
  assert.equal(second.body.lead_id, leadId);
  assert.equal(second.body.created, false);
  assert.equal(await db.activityLog.count({ where: { entity_id: leadId, action_key: "integration.callrail.call" } }), 2);
  assert.equal(await db.acquisitionTouchpoint.count({ where: { lead_id: leadId } }), 1);
  assert.equal((await db.consentSnapshot.findFirst({ where: { lead_id: leadId } }))?.ad_user_data, "UNKNOWN");
  assert.equal(await db.conversionEvent.count({ where: { lead_id: leadId } }), 0);
  const contacted = await db.pipelineStatus.findUniqueOrThrow({ where: { status_code: "CONTACTED" } });
  const initialProject = { id: `callrail-${tag}`, canonicalLeadId: leadId };
  await db.legacyWorkspace.upsert({ where: { workspace_id: "primary" }, create: { workspace_id: "primary", payload: { orders: [initialProject] }, revision: 1 }, update: { payload: { orders: [initialProject] }, revision: { increment: 1 } } });
  assert.equal((await reconcileLegacyGoogleAdsOutcomes()).failed, 0);
  assert.equal(await db.conversionEvent.count({ where: { lead_id: leadId } }), 0, "an enriched linked project without a sent proposal remains unqualified");
  await db.lead.update({ where: { lead_id: leadId }, data: { pipeline_status_id: contacted.pipeline_status_id } });
  assert.equal((await send(fixture("handled-repeat"))).body.lead_id, leadId, "handled callers retain their original project and attribution");
  const status = await db.pipelineStatus.findUniqueOrThrow({ where: { status_code: "NEW_LEAD" } });
  const existing = await db.lead.create({ data: { name: "Existing website fixture", phone: "(202) 555-0199", source: "website", notes: "Preserve staff notes", pipeline_status_id: status.pipeline_status_id } });
  ids.push(existing.lead_id);
  const reused = await send(fixture("website", "+12025550199"));
  assert.equal(reused.body.lead_id, existing.lead_id);
  const unchanged = await db.lead.findUniqueOrThrow({ where: { lead_id: existing.lead_id } });
  assert.equal(unchanged.source, "website");
  assert.equal(unchanged.notes, existing.notes);
  assert.equal(await db.acquisitionTouchpoint.count({ where: { lead_id: existing.lead_id } }), 0);
  assert.equal(await db.consentSnapshot.count({ where: { lead_id: existing.lead_id } }), 0);
  const shared = await db.lead.create({ data: { name: "Shared phone fixture", phone: "+12025550199", source: "website", pipeline_status_id: status.pipeline_status_id } });
  ids.push(shared.lead_id);
  const review = await send(fixture("shared", "+12025550199"));
  ids.push(review.body.lead_id);
  assert.notEqual(review.body.lead_id, existing.lead_id);
  assert.notEqual(review.body.lead_id, shared.lead_id);
  assert.equal((await send(fixture("shared-repeat", "+12025550199"))).body.lead_id, review.body.lead_id);
  assert.match((await db.lead.findUniqueOrThrow({ where: { lead_id: review.body.lead_id } })).notes!, /Общий номер/);
  assert.equal(await db.acquisitionTouchpoint.count({ where: { lead_id: review.body.lead_id } }), 0, "unresolved shared identity cannot claim a new ad click");
  const lost = await db.pipelineStatus.findUniqueOrThrow({ where: { status_code: "CLOSED_LOST" } });
  await db.lead.update({ where: { lead_id: review.body.lead_id }, data: { pipeline_status_id: lost.pipeline_status_id } });
  const nextReview = await send(fixture("resolved-review", "+12025550199"));
  ids.push(nextReview.body.lead_id);
  assert.notEqual(nextReview.body.lead_id, review.body.lead_id, "dismissed review does not swallow future calls");
  const dismissed = await db.lead.create({ data: { name: "Dismissed fixture", phone: "+12025550188", source: "website", pipeline_status_id: status.pipeline_status_id } });
  ids.push(dismissed.lead_id);
  const dismissedResponse = await fetch(base + "/api/v1/leads/" + dismissed.lead_id, { method: "PATCH", headers: { cookie, "content-type": "application/json" }, body: JSON.stringify({ pipeline_status_code: "CLOSED_LOST", expected_status_codes: ["NEW_LEAD"] }) });
  assert.equal(dismissedResponse.status, 200);
  assert.equal((await db.lead.findUniqueOrThrow({ where: { lead_id: dismissed.lead_id }, include: { pipeline_status: true } })).pipeline_status.status_code, "CLOSED_LOST");
  const renewed = await send(fixture("renewed-enquiry", "+12025550188"));
  ids.push(renewed.body.lead_id);
  assert.notEqual(renewed.body.lead_id, dismissed.lead_id, "a dismissed enquiry without a project leaves a fresh call visible");
  const list = await fetch(base + "/api/v1/leads", { headers: { cookie } });
  const items = (await list.json()).data.items;
  assert.equal(items.find((lead: any) => lead.lead_id === leadId).callrail_calls.length, 3);
  assert.equal(items.find((lead: any) => lead.lead_id === leadId).source, "callrail");
  const at = new Date().toISOString();
  const order = { id: `callrail-${tag}`, canonicalLeadId: leadId, timeline: [{ key: "proposal_sent", at }], depositReceived: false, paid: 0, projectEstimateSnapshot: { revenue: 1000 } };
  await db.legacyWorkspace.upsert({ where: { workspace_id: "primary" }, create: { workspace_id: "primary", payload: { orders: [order] }, revision: 1 }, update: { payload: { orders: [order] }, revision: { increment: 1 } } });
  assert.equal((await reconcileLegacyGoogleAdsOutcomes()).failed, 0);
  const qualified = await db.conversionEvent.findFirstOrThrow({ where: { lead_id: leadId, event_type: "qualified_lead" } });
  assert.equal(qualified.event_source, "PHONE");
  order.depositReceived = true; order.paid = 100; order.timeline.push({ key: "accepted_by_payment", at });
  await db.legacyWorkspace.update({ where: { workspace_id: "primary" }, data: { payload: { orders: [order] }, revision: { increment: 1 } } });
  assert.equal((await reconcileLegacyGoogleAdsOutcomes()).failed, 0);
  assert.equal((await reconcileLegacyGoogleAdsOutcomes()).failed, 0);
  const events = await db.conversionEvent.findMany({ where: { lead_id: leadId } });
  assert.equal(events.length, 2);
  assert.ok(events.every(event => event.event_source === "PHONE" && event.attribution_touchpoint_id === qualified.attribution_touchpoint_id));
  assert.equal(await db.conversionUploadOutbox.count({ where: { conversion_event_id: { in: events.map(event => event.conversion_event_id) } } }), 2);
  // The real proposal/payment producers run before the legacy reconciler in the
  // active UI. Their first immutable events must already have PHONE as source.
  const nativeCall = await send(fixture("native-producers", "+12025550177"));
  ids.push(nativeCall.body.lead_id);
  const owner = await db.user.findUniqueOrThrow({ where: { email: "owner@rolanpro.local" } });
  const point = await db.acquisitionTouchpoint.findFirstOrThrow({ where: { lead_id: nativeCall.body.lead_id } });
  const client = await db.client.create({ data: { name: "Offline CallRail native fixture" } });
  clientIds.push(client.client_id);
  const deal = await db.deal.create({ data: { title: "Offline CallRail native fixture", lead_id: nativeCall.body.lead_id, client_id: client.client_id, attribution_touchpoint_id: point.acquisition_touchpoint_id, pipeline_status_id: status.pipeline_status_id, legacy_order_id: `native-callrail-${tag}` } });
  dealIds.push(deal.deal_id);
  const proposal = await db.proposal.create({ data: { deal_id: deal.deal_id, client_id: client.client_id, created_by: owner.user_id, title: "Offline fixture", access_token: `offline-callrail-${tag}`, selected_total_amount: 1000 } });
  await db.$transaction(tx => onProposalSent(tx, { actorUserId: owner.user_id, proposalId: proposal.proposal_id, dealId: deal.deal_id, leadId: nativeCall.body.lead_id }));
  assert.equal((await db.conversionEvent.findFirstOrThrow({ where: { lead_id: nativeCall.body.lead_id, event_type: "qualified_lead" } })).event_source, "PHONE");
  await db.agreement.create({ data: { proposal_id: proposal.proposal_id, status: "signed", signed_at: new Date(), accepted_terms: true } });
  await db.deposit.create({ data: { proposal_id: proposal.proposal_id, status: "paid", paid_at: new Date(), amount: 100 } });
  const closed = await closeSaleIfReady({ proposalId: proposal.proposal_id, actorUserId: owner.user_id });
  assert.ok(closed);
  assert.equal(closed.ready, true);
  const replayed = await closeSaleIfReady({ proposalId: proposal.proposal_id, actorUserId: owner.user_id });
  assert.ok(replayed);
  assert.equal(replayed.ready, true);
  const synchronous = await db.conversionEvent.findMany({ where: { lead_id: nativeCall.body.lead_id } });
  assert.equal(synchronous.length, 2);
  assert.ok(synchronous.every(event => event.event_source === "PHONE" && event.attribution_touchpoint_id === point.acquisition_touchpoint_id));
});
